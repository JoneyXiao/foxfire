#!/usr/bin/env node
/**
 * Reads src/data/bank/<category>.json (source of truth) and regenerates:
 * - src/data/generated/summaries.ts  (no answer — safe for client bundles)
 * - src/data/generated/full.ts       (with answer — server / detail pages)
 *
 * Run via: npm run sync:questions  (also hooked from prebuild / predev)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const bankDir = path.join(root, "src/data/bank");
const outDir = path.join(root, "src/data/generated");

/** Keep category order aligned with CATEGORY_IDS / product taxonomy. */
const CATEGORY_ORDER = [
  "llm-basics",
  "api-structured",
  "prompting",
  "rag",
  "knowledge",
  "agent",
  "harness",
  "frameworks",
  "deployment",
  "evaluation",
  "reliability",
  "safety",
  "product-cost",
  "ml-basics",
];

function readBank() {
  const files = fs
    .readdirSync(bankDir)
    .filter((name) => name.endsWith(".json"))
    .sort((a, b) => {
      const ca = a.replace(/\.json$/, "");
      const cb = b.replace(/\.json$/, "");
      return CATEGORY_ORDER.indexOf(ca) - CATEGORY_ORDER.indexOf(cb);
    });

  if (files.length === 0) {
    throw new Error(`No JSON shards found in ${bankDir}`);
  }

  const questions = [];
  for (const file of files) {
    const category = file.replace(/\.json$/, "");
    const items = JSON.parse(fs.readFileSync(path.join(bankDir, file), "utf8"));
    if (!Array.isArray(items)) {
      throw new Error(`${file} must be a JSON array`);
    }
    for (const item of items) {
      if (item.category !== category) {
        throw new Error(
          `${file}: question ${item.id} has category ${item.category}, expected ${category}`,
        );
      }
      for (const key of ["id", "title", "category", "difficulty", "tags", "prompt", "answer"]) {
        if (!(key in item)) {
          throw new Error(`${file}: question missing field ${key}`);
        }
      }
      questions.push(item);
    }
  }
  return questions;
}

function toTsString(value) {
  return JSON.stringify(value, null, 2);
}

function writeSummaries(questions) {
  const summaries = questions.map(({ answer: _answer, ...rest }) => rest);
  const body = `/* eslint-disable */
// AUTO-GENERATED by scripts/sync-question-data.mjs — do not edit by hand.
// Source of truth: src/data/bank/*.json
import type { QuestionSummary } from "@/lib/types";

export const questionSummaries = ${toTsString(summaries)} as const satisfies readonly QuestionSummary[];
`;
  fs.writeFileSync(path.join(outDir, "summaries.ts"), body, "utf8");
}

function writeFull(questions) {
  const body = `/* eslint-disable */
// AUTO-GENERATED by scripts/sync-question-data.mjs — do not edit by hand.
// Source of truth: src/data/bank/*.json
import type { Question } from "@/lib/types";

export const questions = ${toTsString(questions)} as const satisfies readonly Question[];
`;
  fs.writeFileSync(path.join(outDir, "full.ts"), body, "utf8");
}

fs.mkdirSync(outDir, { recursive: true });
const questions = readBank();
writeSummaries(questions);
writeFull(questions);

const answerChars = questions.reduce((n, q) => n + String(q.answer).length, 0);
console.log(
  `sync-question-data: ${questions.length} questions from ${CATEGORY_ORDER.length} shards; answer chars ≈ ${answerChars}`,
);
