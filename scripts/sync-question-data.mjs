#!/usr/bin/env node
/**
 * Reads src/data/bank/<category>.json (source of truth) and regenerates:
 * - src/data/generated/summaries.ts  (no answer/quotes; prompt omitted when == title)
 * - public/data/questions/<id>.json  (full question — route-level for SSG + client fetch)
 * - src/data/generated/answer-index.ts (plain answer text for optional search)
 * - src/data/generated/checklist-index.ts (mock interview self-check snippets)
 *
 * Run via: npm run sync:questions  (also hooked from prebuild / predev)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const bankDir = path.join(root, "src/data/bank");
const outDir = path.join(root, "src/data/generated");
const publicQuestionsDir = path.join(root, "public/data/questions");

/** Keep category order aligned with CATEGORY_IDS / product taxonomy. */
const CATEGORY_ORDER = [
  "llm-basics",
  "api-structured",
  "prompting",
  "rag",
  "knowledge",
  "agent",
  "harness",
  "frameworks",
  "deployment",
  "evaluation",
  "reliability",
  "safety",
  "product-cost",
  "ml-basics",
];

function readBank() {
  const files = fs
    .readdirSync(bankDir)
    .filter((name) => name.endsWith(".json"))
    .sort((a, b) => {
      const ca = a.replace(/\.json$/, "");
      const cb = b.replace(/\.json$/, "");
      return CATEGORY_ORDER.indexOf(ca) - CATEGORY_ORDER.indexOf(cb);
    });

  if (files.length === 0) {
    throw new Error(`No JSON shards found in ${bankDir}`);
  }

  const questions = [];
  for (const file of files) {
    const category = file.replace(/\.json$/, "");
    const items = JSON.parse(fs.readFileSync(path.join(bankDir, file), "utf8"));
    if (!Array.isArray(items)) {
      throw new Error(`${file} must be a JSON array`);
    }
    for (const item of items) {
      if (item.category !== category) {
        throw new Error(
          `${file}: question ${item.id} has category ${item.category}, expected ${category}`,
        );
      }
      for (const key of ["id", "title", "category", "difficulty", "tags", "prompt", "answer", "interviewQuotes"]) {
        if (!(key in item)) {
          throw new Error(`${file}: question missing field ${key}`);
        }
      }
      if (!Array.isArray(item.interviewQuotes) || item.interviewQuotes.length < 3) {
        throw new Error(`${file}: question ${item.id} needs >=3 interviewQuotes`);
      }
      questions.push(item);
    }
  }
  return questions;
}

function toTsString(value) {
  return JSON.stringify(value, null, 2);
}

/** Strip Markdown to a compact lowercase blob for optional answer keyword search. */
function plainAnswer(md) {
  return String(md)
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/`[^`]+`/g, " ")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/!\[[^\]]*\]\([^)]+\)/g, " ")
    .replace(/^#{1,6}\s+/gm, " ")
    .replace(/^\s*[-*+]\s+/gm, " ")
    .replace(/^\s*\d+\.\s+/gm, " ")
    .replace(/[*_~|>]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

function writeSummaries(questions) {
  // List/client index: drop answer + quotes. When prompt duplicates title, store ""
  // so the home/search chunks stay smaller (UI treats empty prompt as "same as title").
  const summaries = questions.map(({ answer: _a, interviewQuotes: _q, prompt, title, ...rest }) => ({
    ...rest,
    title,
    prompt: String(prompt).trim() === String(title).trim() ? "" : prompt,
  }));
  const body = `/* eslint-disable */
// AUTO-GENERATED by scripts/sync-question-data.mjs — do not edit by hand.
// Source of truth: src/data/bank/*.json
import type { QuestionSummary } from "@/lib/types";

export const questionSummaries = ${toTsString(summaries)} as const satisfies readonly QuestionSummary[];
`;
  fs.writeFileSync(path.join(outDir, "summaries.ts"), body, "utf8");
}

function writeRouteQuestions(questions) {
  fs.mkdirSync(publicQuestionsDir, { recursive: true });
  const existing = new Set(
    fs.readdirSync(publicQuestionsDir).filter((name) => name.endsWith(".json")),
  );
  const keep = new Set();
  for (const item of questions) {
    const name = `${item.id}.json`;
    keep.add(name);
    const target = path.join(publicQuestionsDir, name);
    const payload = JSON.stringify(item);
    fs.writeFileSync(target, payload, "utf8");
  }
  for (const name of existing) {
    if (!keep.has(name)) {
      fs.unlinkSync(path.join(publicQuestionsDir, name));
    }
  }
  // Remove legacy monolithic full.ts if present (answers are route-level JSON now).
  const legacyFull = path.join(outDir, "full.ts");
  if (fs.existsSync(legacyFull)) {
    fs.unlinkSync(legacyFull);
  }
}

function stripInlineMd(text) {
  return String(text)
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/\*([^*]+)\*/g, "$1")
    .replace(/`([^`]+)`/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

/** Body after **Heading** until the next **Section** heading or end. */
function sectionBody(answer, heading) {
  const re = new RegExp(
    `\\*\\*${heading}\\*\\*[：:]?\\s*([\\s\\S]*?)(?=\\n\\*\\*[^*\\n]+\\*\\*|$)`,
  );
  const match = String(answer).match(re);
  return match ? match[1] : "";
}

function extractBullets(block, limit = 8) {
  const bullets = [];
  const seen = new Set();
  for (const rawLine of String(block).split("\n")) {
    const line = rawLine.trim();
    const match = line.match(/^(?:[-*+]|\d+\.)\s+(.+)$/);
    if (!match) continue;
    const text = stripInlineMd(match[1]);
    if (text.length < 8 || /^[-|:]+$/.test(text)) continue;
    const key = text.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    bullets.push(text);
    if (bullets.length >= limit) break;
  }
  return bullets;
}

/**
 * Lightweight self-check payloads for mock interviews (no full answer body).
 * Built from interviewQuotes + 知识点讲解 / 直接答案 bullets already in the bank.
 */
function writeChecklistIndex(questions) {
  const index = {};
  for (const item of questions) {
    const quotes = (item.interviewQuotes || [])
      .map((q) => stripInlineMd(q))
      .filter((q) => q.length > 0)
      .slice(0, 3);
    const knowledge = extractBullets(sectionBody(item.answer, "知识点讲解"), 6);
    const answerBullets = extractBullets(sectionBody(item.answer, "直接答案"), 6);
    index[item.id] = { quotes, knowledge, answerBullets };
  }
  const body = `/* eslint-disable */
// AUTO-GENERATED by scripts/sync-question-data.mjs — do not edit by hand.
// Checklist snippets for mock interview self-check (quotes + answer/knowledge bullets).
// No full reference answers — safe for the /mock client chunk.

export type ChecklistIndexEntry = {
  quotes: readonly string[];
  knowledge: readonly string[];
  answerBullets: readonly string[];
};

export const checklistById = ${JSON.stringify(index)} as const satisfies Readonly<
  Record<string, ChecklistIndexEntry>
>;
`;
  fs.writeFileSync(path.join(outDir, "checklist-index.ts"), body, "utf8");
}

function writeAnswerIndex(questions) {
  const index = Object.fromEntries(
    questions.map((item) => [item.id, plainAnswer(item.answer)]),
  );
  // Compact JSON keeps the optional search chunk smaller than pretty-printed.
  const body = `/* eslint-disable */
// AUTO-GENERATED by scripts/sync-question-data.mjs — do not edit by hand.
// Compact plain-text answer blobs for optional client search (no Markdown).
// Dynamically import only when the user opts into answer keyword search.

export const answerSearchById = ${JSON.stringify(index)} as const satisfies Readonly<Record<string, string>>;
`;
  fs.writeFileSync(path.join(outDir, "answer-index.ts"), body, "utf8");
}

fs.mkdirSync(outDir, { recursive: true });
const questions = readBank();
writeSummaries(questions);
writeRouteQuestions(questions);
writeAnswerIndex(questions);
writeChecklistIndex(questions);

const answerChars = questions.reduce((n, q) => n + String(q.answer).length, 0);
const indexChars = questions.reduce((n, q) => n + plainAnswer(q.answer).length, 0);
const slimPrompts = questions.filter(
  (q) => String(q.prompt).trim() === String(q.title).trim(),
).length;
console.log(
  `sync-question-data: ${questions.length} questions; route JSON in public/data/questions/; answer chars ≈ ${answerChars}; answer-index chars ≈ ${indexChars}; checklist entries = ${questions.length}; slimmed duplicate prompts = ${slimPrompts}`,
);
